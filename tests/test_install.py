"""Tests for install.sh / uninstall.sh.

These tests run the actual installer scripts in a sandbox tempdir using a
synthesized local tarball. They do not touch the real ``$HOME`` because
``LINEAGE_HOME`` and ``LINEAGE_BIN_DIR`` are overridden.

Windows (``install.ps1``) is not exercised here — there is no PowerShell in
the CI image used to run these tests. The Windows installer is kept structurally
parallel to ``install.sh`` so a future Windows test rig can cover it.
"""

from __future__ import annotations

import os
import shutil
import stat
import subprocess
import tarfile
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
INSTALL_SH = REPO_ROOT / "install.sh"
UNINSTALL_SH = REPO_ROOT / "uninstall.sh"


# Skip the whole module on Windows — these scripts are POSIX-only.
pytestmark = pytest.mark.skipif(
    os.name == "nt", reason="install.sh / uninstall.sh are POSIX scripts"
)


def _have(cmd: str) -> bool:
    return shutil.which(cmd) is not None


needs_bash = pytest.mark.skipif(not _have("bash"), reason="bash not on PATH")
needs_tar = pytest.mark.skipif(not _have("tar"), reason="tar not on PATH")


def _build_fake_tarball(src_dir: Path, tarball_path: Path) -> None:
    """Create a tar.gz that mirrors the layout of a real GitHub release.

    GitHub release tarballs have a top-level directory named
    ``lineage-<version>/`` that contains the package contents. ``install.sh``
    uses ``--strip-components=1`` so that directory is removed during extract.
    """
    assert tarfile.is_tarfile.__name__  # touch the stdlib import for sanity
    with tarfile.open(tarball_path, "w:gz") as tf:
        # We add the package directly using a synthetic top-level name.
        # The installer's --strip-components=1 will handle the rest.
        for item in src_dir.iterdir():
            tf.add(item, arcname=f"lineage-test/{item.name}")


