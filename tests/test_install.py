@needs_bash
@needs_tar
def test_install_local_tarball_creates_layout(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    """Run install.sh against a local tarball in a sandbox; verify the layout."""
    fake_home = tmp_path / "home"
    fake_home.mkdir()

    lineage_home = fake_home / ".lineage"
    bin_dir = fake_home / "bin"

    # Build a tarball that contains the actual lineage/ package.
    tarball = tmp_path / "lineage-0.1.0.tar.gz"
    _build_fake_tarball(REPO_ROOT, tarball)

    # Isolate from the real $HOME so the installer's PATH-advice code cannot
    # touch the real ~/.zshrc even by accident.
    monkeypatch.setenv("HOME", str(fake_home))
    monkeypatch.setenv("LINEAGE_HOME", str(lineage_home))
    monkeypatch.setenv("LINEAGE_BIN_DIR", str(bin_dir))

    # Stub the shell init file to a path inside the sandbox so the installer
    # does not write to the user's real rc file.
    fake_rc = fake_home / ".zshrc"
    monkeypatch.setenv("SHELL", "/bin/zsh")
    # Pre-create the rc file in the sandbox so the installer's test is
    # consistent with a real install (it appends to $HOME/.zshrc).
    fake_rc.write_text("# sandbox\n", encoding="utf-8")

    env = os.environ.copy()
    result = subprocess.run(
        ["bash", str(INSTALL_SH), str(tarball)],
        env=env,
        capture_output=True,
        text=True,
        timeout=60,
    )
    if result.returncode != 0:
        print("STDOUT:", result.stdout)
        print("STDERR:", result.stderr)
    assert result.returncode == 0, (
        f"install.sh failed:\n--- stdout ---\n{result.stdout}\n--- stderr ---\n{result.stderr}"
    )

    # Layout assertions
    installed = lineage_home / "0.1.0"
    assert installed.is_dir()
    assert (installed / "lineage").is_dir(), "package must be under <version>/lineage/"
    assert (installed / "lineage" / "cli.py").is_file()

    launcher = bin_dir / "lineage"
    assert launcher.is_file()
    assert launcher.stat().st_mode & stat.S_IXUSR, "launcher must be executable"
    launcher_text = launcher.read_text(encoding="utf-8")
    assert "Auto-generated by the lineage installer" in launcher_text
    assert str(installed) in launcher_text

    pin = lineage_home / ".current"
    assert pin.read_text(encoding="utf-8").strip() == "0.1.0"

    # The installed `lineage` should actually run.
    run = subprocess.run(
        [str(launcher), "--version"],
        env=env,
        capture_output=True,
        text=True,
        timeout=30,
    )
    assert run.returncode == 0, run.stderr
    assert run.stdout.strip().startswith("lineage ")


@needs_bash
@needs_tar
def test_install_then_uninstall(tmp_path: Path, monkeypatch: pytest.MonkeyPatch):
    fake_home = tmp_path / "home"
    fake_home.mkdir()
    lineage_home = fake_home / ".lineage"
    bin_dir = fake_home / "bin"

    tarball = tmp_path / "lineage-0.1.0.tar.gz"
    _build_fake_tarball(REPO_ROOT, tarball)

    monkeypatch.setenv("HOME", str(fake_home))
    monkeypatch.setenv("LINEAGE_HOME", str(lineage_home))
    monkeypatch.setenv("LINEAGE_BIN_DIR", str(bin_dir))
    monkeypatch.setenv("SHELL", "/bin/zsh")
    (fake_home / ".zshrc").write_text("# sandbox\n", encoding="utf-8")

    env = os.environ.copy()

    install = subprocess.run(
        ["bash", str(INSTALL_SH), str(tarball)],
        env=env, capture_output=True, text=True, timeout=60,
    )
    assert install.returncode == 0, install.stderr
    assert (lineage_home / "0.1.0").is_dir()
    assert (bin_dir / "lineage").is_file()

    uninstall = subprocess.run(
        ["bash", str(UNINSTALL_SH)],
        env=env, capture_output=True, text=True, timeout=30,
    )
    assert uninstall.returncode == 0, uninstall.stderr
    assert not lineage_home.exists(), "LINEAGE_HOME should be removed"
    assert not (bin_dir / "lineage").exists(), "launcher should be removed"


