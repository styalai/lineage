@needs_bash
def test_install_rejects_windows_bash():
    """If uname reports a Windows-y string, install.sh should fail clearly."""
    if not _have("uname"):
        pytest.skip("uname not available")
    fake_home = Path("/tmp/lineage_uname_test")  # not actually used; we just want exit code
    env = os.environ.copy()
    env["LINEAGE_HOME"] = str(fake_home / ".lineage")
    env["LINEAGE_BIN_DIR"] = str(fake_home / "bin")
    # Force MINGW by overriding PATH to a shim that prints MINGW64_NT-10.0.
    shim_dir = fake_home / "shim"
    shim_dir.mkdir(parents=True, exist_ok=True)
    uname_shim = shim_dir / "uname"
    uname_shim.write_text("#!/usr/bin/env bash\necho MINGW64_NT-10.0\n", encoding="utf-8")
    uname_shim.chmod(0o755)
    env["PATH"] = str(shim_dir) + ":" + env["PATH"]
    result = subprocess.run(
        ["bash", str(INSTALL_SH), "/dev/null"],
        env=env, capture_output=True, text=True, timeout=10,
    )
    assert result.returncode != 0
    assert "install.ps1" in result.stderr or "Windows" in result.stderr
